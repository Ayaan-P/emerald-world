"""Generate the shared map safety catalog; runtime reads only generated JSON.

Run /usr/bin/python3 -B -m world.build_catalog [--check] after asset changes.
Unknown maps, unresolved source references and malformed allocations fail closed.
"""
import argparse
from functools import lru_cache
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def build_catalog(root=ROOT, *, layout_aware=False):
    root = Path(root)
    arrays = dict(re.findall(r'const u16 (\w+)\[\] = INCBIN_U16\("([^"]+)"\);',
                             (root / 'src/data/tilesets/metatiles.h').read_text()))
    tilesets = {}
    for name, body in re.findall(r'const struct Tileset (\w+)\s*=\s*\{(.*?)\};',
                                 (root / 'src/data/tilesets/headers.h').read_text(), re.S):
        sizes = []
        for field, stride in (('metatiles', 16), ('metatileAttributes', 2)):
            match = re.search(r'\.' + field + r'\s*=\s*(\w+)\s*,', body)
            if match is None:
                raise ValueError('unresolved tileset field: ' + name + '.' + field)
            symbol = match.group(1)
            size = (root / arrays[symbol]).stat().st_size
            if size % stride:
                raise ValueError('misaligned tileset allocation: ' + symbol)
            sizes.append(size // stride)
        tilesets[name] = sizes
    layouts = {layout['id']: layout for layout in json.loads(
        (root / 'data/layouts/layouts.json').read_text())['layouts']}
    groups = json.loads((root / 'data/maps/map_groups.json').read_text())
    maps = []
    for group, label in enumerate(groups['group_order']):
        for num, name in enumerate(groups[label]):
            source = json.loads((root / 'data/maps' / name / 'map.json').read_text())
            layout = layouts[source['layout']]
            width, height = layout['width'], layout['height']
            if any(type(n) is not int or not 0 < n <= 1024 for n in (width, height)):
                raise ValueError('invalid layout dimensions: ' + name)
            version = layout.get('layout_version', 'emerald') if layout_aware else 'emerald'
            if version not in ('emerald', 'frlg'):
                raise ValueError('unknown layout format: ' + str(version))
            secondary_base, attribute_bytes = (640, 4) if version == 'frlg' else (512, 2)
            def count(tileset, maximum):
                metatiles, attributes_u16 = tilesets[tileset]
                if attributes_u16 * 2 % attribute_bytes:
                    raise ValueError('misaligned tileset attributes: ' + tileset)
                return min(maximum, metatiles, attributes_u16 * 2 // attribute_bytes)
            item = dict(group=group, num=num, name=name, layout=source['layout'],
                        width=width, height=height,
                        primary_count=count(layout['primary_tileset'], secondary_base),
                        secondary_count=count(layout['secondary_tileset'], 1024 - secondary_base))
            if layout_aware:
                item.update(secondary_base=secondary_base, attribute_bytes=attribute_bytes)
            maps.append(item)
    return dict(version=2 if layout_aware else 1, primary_base=0, secondary_base=512, maps=maps)


def render_layout_header(catalog):
    if catalog['version'] != 2:
        raise ValueError('layout-aware catalog required')
    lines = ['/* Generated by world/build_catalog.py. Do not edit. */',
             '#ifndef GUARD_PLATFORM_WORLD_CATALOG_H', '#define GUARD_PLATFORM_WORLD_CATALOG_H',
             'struct WorldCatalogMap { unsigned group, num, width, height, primaryCount, secondaryCount, secondaryBase, attributeBytes; };',
             'static const struct WorldCatalogMap sWorldCatalog[] = {']
    for m in catalog['maps']:
        if m['attribute_bytes'] == 4:
            lines.append('#if EW_KANTO_CONTENT')
        lines.append('    {%d, %d, %d, %d, %d, %d, %d, %d},' % tuple(m[k] for k in
                     ('group', 'num', 'width', 'height', 'primary_count', 'secondary_count', 'secondary_base', 'attribute_bytes')))
        if m['attribute_bytes'] == 4:
            lines.append('#endif')
    lines += ['};', 'static const struct WorldCatalogMap *WorldCatalog_Find(unsigned group, unsigned num)',
              '{', '    unsigned i;',
              '    for (i = 0; i < sizeof(sWorldCatalog) / sizeof(sWorldCatalog[0]); i++)',
              '        if (sWorldCatalog[i].group == group && sWorldCatalog[i].num == num) return &sWorldCatalog[i];',
              '    return 0;', '}',
              'static int WorldCatalog_Coords(unsigned group, unsigned num, unsigned x, unsigned y)',
              '{', '    const struct WorldCatalogMap *m = WorldCatalog_Find(group, num);',
              '    return m && x < m->width && y < m->height;', '}',
              'static int WorldCatalog_Metatile(unsigned group, unsigned num, unsigned id)',
              '{', '    const struct WorldCatalogMap *m = WorldCatalog_Find(group, num);',
              '    return m && (id < m->secondaryBase ? id < m->primaryCount : id - m->secondaryBase < m->secondaryCount);',
              '}', '#endif', '']
    return '\n'.join(lines)


def render_header(catalog):
    lines = ['/* Generated by world/build_catalog.py. Do not edit. */',
             '#ifndef GUARD_PLATFORM_WORLD_CATALOG_H', '#define GUARD_PLATFORM_WORLD_CATALOG_H',
             'struct WorldCatalogMap { unsigned group, num, width, height, primaryCount, secondaryCount; };',
             'static const struct WorldCatalogMap sWorldCatalog[] = {']
    for m in catalog['maps']:
        lines.append('    {%d, %d, %d, %d, %d, %d},' % tuple(m[k] for k in
                     ('group', 'num', 'width', 'height', 'primary_count', 'secondary_count')))
    lines += ['};', 'static const struct WorldCatalogMap *WorldCatalog_Find(unsigned group, unsigned num)',
              '{', '    unsigned i;',
              '    for (i = 0; i < sizeof(sWorldCatalog) / sizeof(sWorldCatalog[0]); i++)',
              '        if (sWorldCatalog[i].group == group && sWorldCatalog[i].num == num) return &sWorldCatalog[i];',
              '    return 0;', '}',
              'static int WorldCatalog_Coords(unsigned group, unsigned num, unsigned x, unsigned y)',
              '{', '    const struct WorldCatalogMap *m = WorldCatalog_Find(group, num);',
              '    return m && x < m->width && y < m->height;', '}',
              'static int WorldCatalog_Metatile(unsigned group, unsigned num, unsigned id)',
              '{', '    const struct WorldCatalogMap *m = WorldCatalog_Find(group, num);',
              '    return m && (id < 512 ? id < m->primaryCount : id - 512 < m->secondaryCount);',
              '}', '#endif', '']
    return '\n'.join(lines)


@lru_cache(maxsize=1)
def catalog_maps():
    catalog = json.loads(Path(__file__).with_name('map_catalog.json').read_text())
    if catalog['version'] != 1 or catalog['secondary_base'] != 512 or catalog['primary_base'] != 0:
        raise ValueError('unsupported map catalog')
    return {(m['group'], m['num']): m for m in catalog['maps']}


def validate_coords(group, num, x, y):
    if any(type(v) is not int or v < 0 for v in (group, num, x, y)):
        raise ValueError('invalid map coordinates')
    m = catalog_maps().get((group, num))
    if m is None or x >= m['width'] or y >= m['height']:
        raise ValueError('invalid map coordinates')
    return m


def validate_tile(values):
    group, num, x, y, metatile, collision = values
    m = validate_coords(group, num, x, y)
    if type(metatile) is not int or not (0 <= metatile < m['primary_count'] or
            512 <= metatile < 512 + m['secondary_count']):
        raise ValueError('metatile outside target tileset allocations')
    if type(collision) is not int or collision not in (0, 1):
        raise ValueError('invalid tile collision')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    catalog = build_catalog()
    outputs = {ROOT / 'world/map_catalog.json': json.dumps(catalog, indent=2) + '\n',
               ROOT / 'include/platform/world_catalog.h': render_header(catalog)}
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('stale generated catalog: ' + str(path))
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
