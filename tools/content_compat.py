#!/usr/bin/env python3
"""Versioned native source identity, shared by the binary and packaged authority.

Run after source integration and before packaging. Never derive the host ID from
its mutable world directory or from a client's claim. Generated asset encodings
are excluded so building on different platforms cannot change the source ID.
"""
import argparse
import hashlib
import json
from pathlib import Path

SCHEMA = 1
HEADER = Path('include/platform/content_compat_generated.h')
MANIFEST = Path('world/content_compat.json')
GENERATED_SUFFIXES = {'.1bpp', '.4bpp', '.8bpp', '.gbapal', '.lz', '.rl', '.o', '.d', '.pyc',
                      '.i', '.smol', '.fastSmol', '.smolTM', '.latfont', '.hwjpnfont', '.fwjpnfont'}
# Outputs of map_data_rules.mk, json_data_rules.mk and graphics_file_rules.mk.
# Their JSON/templates/source images, rather than build-dependent outputs, hash.
GENERATED_PATHS = {
    HEADER.as_posix(), 'data/layouts/layouts.inc', 'data/layouts/layouts_table.inc',
    'data/maps/connections.inc', 'data/maps/events.inc', 'data/maps/groups.inc', 'data/maps/headers.inc',
    'include/constants/map_groups.h', 'include/constants/layouts.h', 'include/constants/map_event_ids.h',
    'include/constants/wild_encounter.h', 'include/constants/region_map_sections.h',
    'include/constants/heal_locations.h', 'src/data/wild_encounters.h',
    'src/data/region_map/region_map_entries.h', 'src/data/heal_locations.h',
    'graphics/unused/redyellowgreen_frame.bin',
}
GENERATOR_DIRS = ('tools/mapjson', 'tools/jsonproc', 'tools/gbagfx', 'tools/preproc')
GENERATOR_SUFFIXES = {'.c', '.cpp', '.h', '.hpp'}
TEXT_SUFFIXES = {'.c', '.cpp', '.h', '.hpp', '.s', '.inc', '.txt', '.json', '.pal', '.py'}


def content_id(root):
    root = Path(root)
    files = [root/'tools/content_compat.py']
    for directory in GENERATOR_DIRS:
        files.extend(p for p in (root/directory).rglob('*')
                     if p.is_file() and p.suffix in GENERATOR_SUFFIXES)
    for directory in ('src', 'include', 'data', 'graphics'):
        files.extend(p for p in (root/directory).rglob('*')
                     if p.is_file() and p.relative_to(root).as_posix() not in GENERATED_PATHS
                     and not (p.relative_to(root).as_posix().startswith('data/maps/')
                              and p.name in {'connections.inc', 'events.inc', 'header.inc'})
                     and p.suffix not in GENERATED_SUFFIXES
                     and not any(part.startswith('.') or part == '__pycache__'
                                 for part in p.relative_to(root).parts))
    digest = hashlib.sha256(b'emerald-native-content-v1\0')
    for path in sorted(files, key=lambda p: p.relative_to(root).as_posix()):
        name = path.relative_to(root).as_posix().encode('utf-8')
        data = path.read_bytes()
        if (path.suffix in TEXT_SUFFIXES
                and (path.suffix != '.pal' or data.startswith(b'JASC-PAL'))):
            data = data.replace(b'\r\n', b'\n')
        # Length framing makes path/content boundaries unambiguous.
        for value in (name, data):
            digest.update(len(value).to_bytes(8, 'big'))
            digest.update(value)
    return digest.hexdigest()


def _write_changed(path, data):
    if path.exists() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def generate(root):
    root = Path(root)
    tag = content_id(root)
    _write_changed(root/HEADER, ('/* Generated by tools/content_compat.py. */\n'
        '#ifndef GUARD_CONTENT_COMPAT_GENERATED_H\n#define GUARD_CONTENT_COMPAT_GENERATED_H\n'
        f'#define WORLD_CONTENT_ID "{tag}"\n#endif\n').encode('ascii'))
    _write_changed(root/MANIFEST, (json.dumps(dict(schema=SCHEMA, content_id=tag),
        sort_keys=True, indent=2) + '\n').encode('ascii'))
    return tag


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    print(generate(args.root))
