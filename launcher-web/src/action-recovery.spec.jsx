// @vitest-environment jsdom
import React from 'react';
import { afterEach, expect, it, vi } from 'vitest';
import { act, cleanup, fireEvent, render, screen, within } from '@testing-library/react';
import { App } from './main';
import { loadState, perform } from './api';
vi.mock('./api', () => ({ loadState: vi.fn(), perform: vi.fn(), forgetCapability: vi.fn() }));
const base = { engine: 'expansion-native', local_worlds: [], local_hosts: [], worlds: [], offline_saves: [], presence: null, hosting: { available: false, enrolled: false, loaded: false, worlds: [], pending: null }, connected: false, trainer: null, games: [], setup: [], status: 'Ready' };
afterEach(() => { cleanup(); vi.useRealTimers(); vi.resetAllMocks(); });
async function start() {
  vi.useFakeTimers(); loadState.mockResolvedValue(base);
  render(<App />);
  await act(async () => {});
  fireEvent.click(screen.getByRole('button', { name: 'Create local world' }));
  fireEvent.change(screen.getByLabelText('World name'), { target: { value: 'Original world' } });
  fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Create and play' }));
}
it('bounds an unresolved action, resumes status access and Escape/navigation without retrying', async () => {
  perform.mockImplementation(() => new Promise(() => {}));
  await start();
  await act(async () => { await vi.advanceTimersByTimeAsync(30000); });
  expect(screen.getByText(/outcome unknown/i)).toBeTruthy();
  expect(screen.getByText(/does not cancel/i)).toBeTruthy();
  expect(loadState.mock.calls.length).toBeGreaterThan(1);
  fireEvent.keyDown(document, { key: 'Escape' });
  expect(screen.queryByRole('dialog')).toBeNull();
  fireEvent.click(within(screen.getByRole('navigation')).getByRole('button', { name: 'Controls & help' }));
  expect(screen.getByRole('heading', { name: 'Controls & help' })).toBeTruthy();
  fireEvent.click(screen.getByRole('button', { name: /check launcher state/i }));
  await act(async () => {});
  expect(perform.mock.calls).toEqual([['local_create', { name: 'Original world', trainer: 'Player' }]]);
});
it('discards a late success and reads the current session instead of launching into a changed target', async () => {
  let finish;
  perform.mockImplementation(() => new Promise(resolve => { finish = resolve; }));
  await start();
  await act(async () => { await vi.advanceTimersByTimeAsync(30000); });
  fireEvent.keyDown(document, { key: 'Escape' });
  const current = { ...base, connected: true, world_key: 'other', trainer: 'May', worlds: [{ key: 'other', name: 'Current world', trainer: 'May' }] };
  loadState.mockResolvedValue(current);
  await act(async () => { await vi.advanceTimersByTimeAsync(5000); });
  expect(screen.getByRole('region', { name: 'Current session' }).textContent).toContain('May');
  fireEvent.click(screen.getByRole('button', { name: 'Play now' }));
  expect(perform).toHaveBeenCalledTimes(1);
  await act(async () => { finish({ ...base, connected: true, world_key: 'old', trainer: 'OldTrainer' }); });
  expect(screen.queryByText(/outcome unknown/i)).toBeNull();
  expect(screen.getByRole('region', { name: 'Current session' }).textContent).toContain('May');
  expect(screen.getByRole('region', { name: 'Current session' }).textContent).not.toContain('OldTrainer');
  expect(perform.mock.calls.map(call => call[0])).toEqual(['local_create']);
  expect(screen.getByRole('alert').textContent).toMatch(/late response was not applied/);
});
it('keeps the action gate after late failure until a post-settlement read succeeds', async () => {
  let fail;
  perform.mockImplementation(() => new Promise((resolve, reject) => { fail = reject; }));
  await start();
  await act(async () => { await vi.advanceTimersByTimeAsync(30000); });
  loadState.mockRejectedValue(new Error('Readback offline'));
  await act(async () => { fail(new Error('Response lost after write')); });
  expect(screen.getByText(/outcome unknown/i)).toBeTruthy();
  expect(screen.getByRole('alert').textContent).toContain('Readback offline');
  fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Create and play' }));
  expect(perform).toHaveBeenCalledTimes(1);
  fireEvent.keyDown(document, { key: 'Escape' });
  loadState.mockResolvedValue(base);
  fireEvent.click(screen.getByRole('button', { name: 'Check launcher state' }));
  await act(async () => {});
  expect(screen.queryByText(/outcome unknown/i)).toBeNull();
  expect(screen.getByRole('alert').textContent).toMatch(/changes may already have happened/);
  expect(perform).toHaveBeenCalledTimes(1);
});
it('reads back a slow successful adventure install without replaying apply or accepting its stale page response', async () => {
  vi.useFakeTimers();
  const world = { key: 'local', name: 'Original world', trainer: 'Player' };
  const state = { ...base, connected: true, local_host: true, world_key: 'local', trainer: 'Player', local_worlds: [world], local_hosts: ['local'] };
  loadState.mockResolvedValue(state);
  let finish, installed = false;
  perform.mockImplementation((action) => {
    if (action === 'adventure_read') return Promise.resolve({ saved: installed, guide: [installed ? 'Readback confirms installed route' : 'Not installed'] });
    if (action === 'adventure_preview') return Promise.resolve({ token: 'review-original', label: 'Lantern Trail' });
    if (action === 'adventure_apply') return new Promise(resolve => { finish = () => { installed = true; resolve({ saved: true, guide: ['STALE APPLY SNAPSHOT'] }); }; });
    throw new Error(`Unexpected action: ${action}`);
  });
  render(<App />);
  await act(async () => {});
  fireEvent.click(screen.getByRole('button', { name: 'Lantern Trail' }));
  await act(async () => {});
  fireEvent.click(screen.getByRole('button', { name: 'Review Lantern Trail' }));
  await act(async () => {});
  fireEvent.click(screen.getByRole('checkbox'));
  fireEvent.click(screen.getByRole('button', { name: 'Install reviewed adventure' }));
  await act(async () => { await vi.advanceTimersByTimeAsync(30000); });
  expect(screen.queryByRole('button', { name: 'Install reviewed adventure' })).toBeNull();
  expect(screen.getByText(/outcome unknown/i)).toBeTruthy();
  await act(async () => { finish(); });
  expect(screen.queryByText('STALE APPLY SNAPSHOT')).toBeNull();
  fireEvent.click(screen.getByRole('button', { name: 'Refresh adventure' }));
  await act(async () => {});
  expect(screen.getByText('Readback confirms installed route')).toBeTruthy();
  expect(perform.mock.calls.filter(([a]) => a === 'adventure_apply')).toEqual([['adventure_apply', { world: 'local', token: 'review-original', confirmed: true }]]);
});
it('does not falsely report that a timed-out launch failed or send a second launch', async () => {
  let finish;
  const connected = { ...base, connected: true, world_key: 'original', trainer: 'Player' };
  perform.mockResolvedValueOnce(connected).mockImplementationOnce(() => new Promise(resolve => { finish = resolve; }));
  await start();
  await act(async () => {});
  expect(perform.mock.calls.map(([action]) => action)).toEqual(['local_create', 'launch']);
  await act(async () => { await vi.advanceTimersByTimeAsync(30000); });
  expect(screen.getByText(/outcome unknown/i)).toBeTruthy();
  expect(screen.queryByText(/game did not start/i)).toBeNull();
  const running = { ...connected, games: ['Player'] };
  loadState.mockResolvedValue(running);
  await act(async () => { finish(running); });
  expect(screen.getByRole('region', { name: 'Current session' }).textContent).toContain('Waiting for game connection');
  expect(perform.mock.calls.map(([action]) => action)).toEqual(['local_create', 'launch']);
});
it('reports a prompt server error and releases busy without retry', async () => {
  perform.mockRejectedValue(new Error('World is unavailable'));
  await start();
  await act(async () => {});
  expect(screen.getByRole('alert').textContent).toContain('World is unavailable');
  expect(within(screen.getByRole('dialog')).getByRole('button', { name: 'Cancel' }).disabled).toBe(false);
  expect(perform).toHaveBeenCalledTimes(1);
});
