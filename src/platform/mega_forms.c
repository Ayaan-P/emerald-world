const struct MegaFormData *MegaForm_Get(u8 form)
{
    return form > MEGA_FORM_NONE && form < MEGA_FORM_COUNT ? &sMegaForms[form] : NULL;
}
u8 MegaForm_Find(u16 species, u8 stone)
{
    u8 i;
    if (!species || !stone) return MEGA_FORM_NONE;
    for (i = 1; i < MEGA_FORM_COUNT; i++)
        if (sMegaForms[i].baseSpecies == species && sMegaForms[i].stone == stone) return i;
    return MEGA_FORM_NONE;
}

u8 MegaForm_FirstStone(u16 species)
{
    u8 i;
    if (!species) return MEGA_STONE_NONE;
    for (i = 1; i < MEGA_FORM_COUNT; i++)
        if (sMegaForms[i].baseSpecies == species) return sMegaForms[i].stone;
    return MEGA_STONE_NONE;
}

