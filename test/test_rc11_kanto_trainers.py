"""Real regional trainer hooks with upstream assembled bytecode and native saves.

Requires canonical trainer headers generated by the combined native build.
Only the unavailable dynamic-character and debug-AI adapters are stubbed;
slide text encoding is outside this test's scope.
"""
import re
import subprocess
import unittest
from pathlib import Path
from test import test_rc7_region_state as region
ENGINE = region.ENGINE


class KantoTrainerIntegration(unittest.TestCase):
    run_command = classmethod(region.RegionStateIntegration.run_command.__func__)

    @classmethod
    def setUpClass(cls):
        region.RegionStateIntegration.setUpClass.__func__(cls)

    def test_upstream_trainers_bytecode_and_separate_saved_defeat_banks(self):
        d = self.directory
        flags = [*self.flags, '-DEW_REGION_STATE=1', '-DEW_KANTO_CONTENT=1']
        prefix = (ENGINE / 'data/event_scripts.s').read_text().split('\t.section script_data', 1)[0]
        line = next(s for s in (ENGINE / 'data/maps/ViridianForest_Frlg/scripts.inc').read_text().splitlines()
                    if 'trainerbattle_single TRAINER_BUG_CATCHER_RICK,' in s)
        assembly = prefix + '\n.section .rodata\n.global TestKantoTrainer, TestKantoCheck, TestKantoSet, TestKantoClear\n'
        assembly += 'TestKantoTrainer:\n' + line + '\n'
        for label, cmd in [('Check', 'checktrainerflag'), ('Set', 'settrainerflag'), ('Clear', 'cleartrainerflag')]:
            assembly += f'TestKanto{label}:\n {cmd} TRAINER_BUG_CATCHER_RICK\n'
        assembly += 'ViridianForest_Text_RickIntro:\nViridianForest_Text_RickDefeat:\n.byte 0\n'
        source = d / 'trainer.s'
        source.write_text(assembly)
        commands = [
            ['tools/preproc/preproc', '-s', str(source), 'charmap.txt'],
            ['gcc', '-E', '-x', 'c', '-Iinclude', '-I.', '-DPLATFORM_NATIVE=1', '-DMODERN=1',
             '-DEMERALD', '-DPORTABLE=1', '-DTESTING=0', '-DEW_REGION_STATE=1', '-DEW_KANTO_CONTENT=1', '-'],
            ['tools/preproc/preproc', '-ie', str(source), 'charmap.txt'],
            ['python3', '-I', 'platform/build_glue/asm_filter.py', '--pointer-size', '8', '--input', 'data'],
            ['as', '--64', '--noexecstack', '--defsym', 'MODERN=1', '--defsym', 'EMERALD=1',
             '--defsym', 'PLATFORM_NATIVE=1', '--defsym', 'NATIVE_POINTER_SIZE_8=1', '-o', str(d / 'trainer-asm.o')],
        ]
        data = None
        for command in commands:
            p = subprocess.run(command, input=data, capture_output=True, cwd=ENGINE)
            self.assertEqual(p.returncode, 0, p.stderr.decode(errors='replace'))
            data = p.stdout
        wrapper = d / 'trainers.c'
        def function(path, name):
            text = (ENGINE / path).read_text()
            return re.search(r'^\w+ ' + name + r'\([^\n]*\)\n\{.*?^\}', text, re.M | re.S).group()
        wrapper.write_text('''#include "tests/rc8/region_trainers.c"
const struct Trainer *WorldCharacter_Trainer(u16 id) { (void)id; return NULL; }
''' + function('src/pokemon.c', 'GetTrainerEncounterMusicId') + '\n'
            + function('src/battle_util.c', 'AreMultiPartiesFullTeams'))
        data_source = (ENGINE / 'src/data.c').read_text()
        partner_source = (ENGINE / 'src/battle_partner.c').read_text()
        tables = d / 'tables.c'
        tables.write_text('#define _(s) s\n' + data_source.split('const u16 gMinigameDigits_Pal')[0]
                          + data_source[data_source.index('#if !TESTING'):data_source.index('#include "data/trainer_approach_music.h"')]
                          + partner_source[:partner_source.index('#define STEVEN_OTID')])
        slides = d / 'slides.c'
        slides.write_text('''#include <assert.h>
/* Slide availability, not text encoding, is under test. */
#define COMPOUND_STRING(s) ((const unsigned char *)(s))
#include "src/trainer_slide.c"
void TestKantoSlides(void) {
 for (unsigned id=KANTO_TRAINERS_START+1;id<KANTO_TRAINERS_START+TRAINERS_COUNT_FRLG;id++)
  for(unsigned s=0;s<TRAINER_SLIDE_COUNT;s++)
   assert(!DoesTrainerHaveSlideMessage(DIFFICULTY_NORMAL,id,s));
}
''')
        for name in ('trainers', 'slides', 'tables'):
            self.run_command(['gcc', *flags, *self.game_includes, '-iquote', 'src', '-c', str(d / f'{name}.c'), '-o', str(d / f'{name}.o')])
        binary = d / 'trainers'
        self.run_command(['gcc', *flags, '-Iplatform', '-idirafter', 'include', '-iquote', '.', *self.link,
                          str(d / 'trainers.o'), str(d / 'slides.o'), str(d / 'trainer-asm.o'),
                          str(d / 'tables.o'), *self.platform, '-o', str(binary)])
        self.assertIn('independent saved profiles passed', self.run_command([str(binary)]))


if __name__ == '__main__':
    unittest.main()
